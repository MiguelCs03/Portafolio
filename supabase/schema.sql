-- ------------------------------------------------------------------ TABLAS ---

create table if not exists public.portfolio_visits (
  id                uuid primary key,
  visitor_id        text not null,
  session_id        text not null,
  path              text,
  referrer          text,
  referrer_host     text,
  utm_source        text,
  utm_medium        text,
  utm_campaign      text,
  country_code      text,
  country_name      text,
  city              text,
  device_type       text,
  browser           text,
  os                text,
  screen_width      integer,
  screen_height     integer,
  language          text,
  timezone          text,
  duration_seconds  integer not null default 0,
  scroll_depth      integer not null default 0,
  created_at        timestamptz not null default now(),
  last_seen_at      timestamptz not null default now()
);

create table if not exists public.portfolio_events (
  id          bigint generated by default as identity primary key,
  visitor_id  text not null,
  session_id  text not null,
  visit_id    uuid,
  event_type  text not null,
  event_name  text,
  metadata    jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);

create index if not exists portfolio_visits_created_at_idx on public.portfolio_visits (created_at desc);
create index if not exists portfolio_visits_session_idx    on public.portfolio_visits (session_id);
create index if not exists portfolio_visits_visitor_idx    on public.portfolio_visits (visitor_id);
create index if not exists portfolio_events_created_at_idx on public.portfolio_events (created_at desc);
create index if not exists portfolio_events_type_idx       on public.portfolio_events (event_type);

-- --------------------------------------------------------------- SEGURIDAD ---

alter table public.portfolio_visits enable row level security;
alter table public.portfolio_events enable row level security;

-- Cualquier visitante puede INSERTAR su visita (necesario para medir).
drop policy if exists "visits_insert_public" on public.portfolio_visits;
create policy "visits_insert_public"
  on public.portfolio_visits
  for insert
  to anon, authenticated
  with check (true);

-- Solo un usuario autenticado (tú) puede LEER o BORRAR las visitas.
drop policy if exists "visits_read_authenticated" on public.portfolio_visits;
create policy "visits_read_authenticated"
  on public.portfolio_visits
  for select
  to authenticated
  using (true);

drop policy if exists "visits_delete_authenticated" on public.portfolio_visits;
create policy "visits_delete_authenticated"
  on public.portfolio_visits
  for delete
  to authenticated
  using (true);

drop policy if exists "events_insert_public" on public.portfolio_events;
create policy "events_insert_public"
  on public.portfolio_events
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "events_read_authenticated" on public.portfolio_events;
create policy "events_read_authenticated"
  on public.portfolio_events
  for select
  to authenticated
  using (true);

drop policy if exists "events_delete_authenticated" on public.portfolio_events;
create policy "events_delete_authenticated"
  on public.portfolio_events
  for delete
  to authenticated
  using (true);

-- Permisos base (RLS sigue siendo la barrera real).
grant insert on public.portfolio_visits to anon, authenticated;
grant select, delete on public.portfolio_visits to authenticated;
grant insert on public.portfolio_events to anon, authenticated;
grant select, delete on public.portfolio_events to authenticated;

-- --------------------------------------------------- ACTUALIZAR DURACIÓN ---
-- El navegador anónimo no puede hacer UPDATE directo (sería inseguro).
-- Esta función SECURITY DEFINER solo actualiza duración/scroll de una visita
-- existente y limita los valores a rangos razonables.

create or replace function public.portfolio_touch_visit(
  p_visit_id uuid,
  p_seconds  integer,
  p_scroll   integer
)
returns void
language sql
security definer
set search_path = public
as $$
  update public.portfolio_visits
     set duration_seconds = greatest(duration_seconds, least(greatest(p_seconds, 0), 7200)),
         scroll_depth     = greatest(scroll_depth, least(greatest(p_scroll, 0), 100)),
         last_seen_at     = now()
   where id = p_visit_id;
$$;

revoke all on function public.portfolio_touch_visit(uuid, integer, integer) from public;
grant execute on function public.portfolio_touch_visit(uuid, integer, integer) to anon, authenticated;

